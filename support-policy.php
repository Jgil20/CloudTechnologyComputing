    <li>Website contact or consultation form</li>
    <li>Any dedicated support channel identified in the customer’s service agreement Please include the affected service, a description of the problem, screenshots or error messages, when the issue began, and any recent changes that may be relevant.</li>
  </ul>
</section>

<section class="legal-section" id="section-2-support-availability">
  <h2>2. Support Availability</h2>
  <p>General support requests are reviewed during normal business operations. Response times depend on the customer’s service plan, the severity of the issue, available staff, and whether the issue involves a third-party platform. Emergency, after-hours, holiday, or 24/7 support is available only when included in a written managed-services agreement.</p>
</section>

<section class="legal-section" id="section-3-issue-priority">
  <h2>3. Issue Priority</h2>
  <p>Support requests may be classified as follows: Critical: A production website, application, cloud environment, or essential business system is unavailable, and no reasonable workaround exists. High: A major feature is unavailable or significantly impaired, but some business operations remain available. Normal: A limited feature is affected, a workaround exists, or the request involves configuration, troubleshooting, or maintenance.</p>
  <p>Low: A general question, enhancement request, cosmetic issue, content update, or non-urgent change. Priority classifications may be adjusted after technical review.</p>
</section>

<section class="legal-section" id="section-4-response-and-resolution">
  <h2>4. Response and Resolution</h2>
  <ul>
    <li>Any stated response time is a target for acknowledging or beginning review of a request. It is not a guaranteed resolution time. Resolution may depend on:</li>
    <li>Customer access and cooperation</li>
    <li>Hosting-provider availability</li>
    <li>Software vendors and cloud providers</li>
    <li>Domain, DNS, email, or payment processors</li>
    <li>Security investigations</li>
    <li>Third-party APIs and integrations</li>
    <li>The complexity and scope of the problem Cloud Technology Computing will provide reasonable updates while an active support request is being investigated.</li>
  </ul>
</section>

<section class="legal-section" id="section-5-customer-responsibilities">
  <h2>5. Customer Responsibilities</h2>
  <ul>
    <li>Customers are responsible for:</li>
    <li>Providing accurate information and authorized access</li>
    <li>Maintaining current contact and billing information</li>
    <li>Protecting passwords and administrator credentials</li>
    <li>Following security recommendations</li>
    <li>Maintaining valid third-party subscriptions and licenses</li>
    <li>Reporting suspected security incidents promptly</li>
    <li>Avoiding unauthorized changes while troubleshooting is underway Delays caused by missing access, incomplete information, unsupported software, or customer-controlled systems may affect response and resolution times.</li>
  </ul>
</section>

<section class="legal-section" id="section-6-supported-services">
  <h2>6. Supported Services</h2>
  <ul>
    <li>Support applies only to services, systems, applications, and configurations covered by an active agreement or approved project scope. Additional fees may apply for:</li>
    <li>Work outside the agreed scope</li>
    <li>New features or redesigns</li>
    <li>Data recovery</li>
    <li>Malware remediation</li>
    <li>Emergency work</li>
    <li>Third-party migration</li>
    <li>Unsupported or outdated systems</li>
    <li>Damage caused by unauthorized changes Approval may be required before billable work begins.</li>
  </ul>
</section>

<section class="legal-section" id="section-7-third-party-services">
  <h2>7. Third-Party Services</h2>
  <p>Some services depend on third parties such as AWS, Microsoft Azure, Google Cloud, IBM Cloud, Hostinger, Cloudflare, Stripe, PayPal, domain registrars, software vendors, and API providers. Cloud Technology Computing may assist with troubleshooting, but cannot guarantee the availability, performance, policies, security, or response times of third-party services.</p>
</section>

<section class="legal-section" id="section-8-backups-and-data-recovery">
  <h2>8. Backups and Data Recovery</h2>
  <p>Backups are provided only when included in the customer’s service plan or project agreement. Customers should maintain independent copies of important business data. No backup or recovery system can guarantee that every file or version will be recoverable. Restoration work may be billed separately unless expressly included in the customer’s agreement.</p>
</section>

<section class="legal-section" id="section-9-security-incidents">
  <h2>9. Security Incidents</h2>
  <p>Suspected unauthorized access, malware, credential theft, or data exposure should be reported immediately. Cloud Technology Computing may temporarily restrict access, disable integrations, reset credentials, isolate affected systems, or recommend additional security measures when reasonably necessary to protect systems and data.</p>
</section>

<section class="legal-section" id="section-10-policy-changes">
  <h2>10. Policy Changes</h2>
  <p>This Support Policy may be updated as services, technologies, and business practices change. The updated version will be posted on the website with a revised effective date.</p>
</section>


                    
